package cli

// ManPage returns the cbor-tool manual page in groff(7) man format.
func ManPage() string {
	return `.TH CBOR-TOOL 1 - "CBOR-tools" "User Commands"
.SH NAME
cbor-tool \- encode, decode, and tag CBOR data
.SH SYNOPSIS
.B cbor-tool
.RI [ options ]
.SH DESCRIPTION
.B cbor-tool
encodes, decodes, and tags CBOR (Concise Binary Object Representation,
RFC 8949) data. Input is read from standard input, from a file named by
.BR \-f ,
or from the literal string given by
.BR \-s .
Output is written to standard output, or to a file named by
.BR \-o .
.PP
Writes to a file are atomic: the data is staged in a temporary file in the
destination directory and renamed into place, so an interrupted run never
leaves a partially written file behind. Devices, sockets, and pipes named by
.B \-o
are written directly because they cannot be replaced by a rename.
.SH ACTIONS
.TP
.BI \-a " ACTION"
Selects the action to perform. Exactly one of the following is required.
.RS
.TP
.B Encode
Encode the input string as a CBOR text string.
.TP
.B Decode
Decode CBOR input and print it as JSON.
.TP
.B Tag
Wrap a CBOR value in the CBOR tag number given by
.BR \-t .
.RE
.SH OPTIONS
.TP
.BI \-f " FILE"
Read input from
.I FILE
instead of standard input.
.TP
.BI \-s " STRING"
Use
.I STRING
as the input of
.B Encode
or
.BR Tag .
When
.B \-s
is given,
.B \-f
and standard input are ignored.
.TP
.BI \-t " NUMBER"
CBOR tag number, required by the
.B Tag
action.
.TP
.BI \-o " FILE"
Write output to
.I FILE
instead of standard output.
.TP
.BI \-format " FORMAT"
Output format for
.BR Decode :
.B pretty
(indented, default) or
.BR json .
.TP
.BI \-root " DIRECTORY"
Confine file access to
.IR DIRECTORY .
Input and output paths are then resolved inside that directory tree and any
path that would escape it is rejected by the operating system.
.TP
.BI \-completion " SHELL"
Print a shell completion script for
.I SHELL
(bash, zsh, or fish) and exit. Combine with
.B \-o
to write it to a file.
.TP
.B \-man
Print this manual page and exit.
.TP
.B \-q
.TQ
.B \-quiet
Suppress diagnostics on standard error. The exit code still reports success
or failure.
.TP
.B \-version
.TQ
.B \-v
Print the version and exit.
.SH EXIT STATUS
.TP
.B 0
Success.
.TP
.B 1
Runtime error: invalid input or I/O failure.
.TP
.B 2
Flag parsing error.
.SH EXAMPLES
.PP
Encode a string and print the CBOR bytes:
.PP
.RS
.EX
printf 'hello' | cbor-tool -a Encode
.EE
.RE
.PP
Decode a file as pretty printed JSON:
.PP
.RS
.EX
cbor-tool -a Decode -f hello.cbor
.EE
.RE
.PP
Tag a value and write it to a file:
.PP
.RS
.EX
cbor-tool -a Tag -t 42 -s 'hello' -o tagged.cbor
.EE
.RE
.PP
Restrict all file access to a working directory:
.PP
.RS
.EX
cbor-tool -root /srv/cbor -a Decode -f incoming.cbor
.EE
.RE
.SH FILES
.TP
.I completions/cbor-tool.bash
Bash completion script, generated by
.BR "cbor-tool -completion bash" .
.TP
.I completions/_cbor-tool
Zsh completion script, generated by
.BR "cbor-tool -completion zsh" .
.TP
.I completions/cbor-tool.fish
Fish completion script, generated by
.BR "cbor-tool -completion fish" .
.SH SEE ALSO
.BR cbor (7)
.SH AUTHORS
The CBOR-tools contributors.
`
}
